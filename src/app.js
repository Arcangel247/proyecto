import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import { authRoutes } from './presentation/routes/auth.routes.js';
import { walletRoutes } from './presentation/routes/wallet.routes.js';
import { transactionRoutes } from './presentation/routes/transaction.routes.js';
import { categoryRoutes } from './presentation/routes/category.routes.js';
import { currencyRoutes } from './presentation/routes/currency.routes.js';
import { budgetRoutes } from './presentation/routes/budget.routes.js';
import { reportRoutes } from './presentation/routes/report.routes.js';
import { errors } from './presentation/middlewares/errors.js';
import { installSwagger } from './presentation/docs/swagger.js';
export const app=express();app.use(cors());app.use(express.json({limit:'100kb'}));installSwagger(app);
app.get('/api/v1/health',(req,res)=>res.json({status:'OK',message:'API de Gestor de Finanzas activa'}));
app.use('/api/v1/auth',authRoutes);app.use('/api/v1/wallets',walletRoutes);app.use('/api/v1/transactions',transactionRoutes);app.use('/api/v1/categories',categoryRoutes);app.use('/api/v1/currencies',currencyRoutes);app.use('/api/v1/budgets',budgetRoutes);app.use('/api/v1/reports',reportRoutes);
app.use((req,res)=>res.status(404).json({error:'Ruta no encontrada'}));app.use(errors);
